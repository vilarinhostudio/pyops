    @classmethod
    def _sun_values(cls, holder, epw, period, suns):
        """The chosen climate variable at each sun's own hour.

        Suns are filtered to daylight, so they are a subset of the period and
        can't be zipped against the collection directly — the value is looked up
        by hour of year instead."""
        if holder.sun_value_variable == "NONE" or epw is None:
            return None
        data = lb.apply_period(lb.epw_field(epw, holder.sun_value_variable), period)
        if data is None:
            return None
        try:
            hoys = list(data.header.analysis_period.hoys)
            lookup = {round(hoy, 3): value for hoy, value in zip(hoys, data.values)}
        except Exception as e:
            print(f"[PyOps.ladybug] valores por hora indisponíveis: {e}")
            return None
        values = [lookup.get(round(sun.hoy, 3)) for sun in suns]
        if any(value is None for value in values):
            average = sum(v for v in values if v is not None) / max(
                sum(1 for v in values if v is not None), 1
            )
            values = [average if value is None else value for value in values]
        return values

