    @classmethod
    def _chart_dims(cls, reference, holder, natural_x, natural_y, span_x, span_y):
        """Axis dimensions for a 2D chart, honouring the fit mode.

        X only and Y only mean "size this axis to the parent and let the other
        follow" — they were sizing BOTH to the same extent, which squashed the
        humidity axis by a factor of a thousand. Fitting one axis now yields a
        single scale factor applied to both, so the chart keeps its proportions.

        None takes Ladybug's own dimensions, multiplied by the scale input,
        which previously did nothing in that mode."""
        mode = holder.chart_fit
        scale = max(holder.scale, 1e-6)

        if mode == "NONE":
            return natural_x * scale, natural_y * scale
        if mode == "X":
            factor = (reference.width / span_x) / natural_x
            return natural_x * factor, natural_y * factor
        if mode == "Y":
            factor = (reference.depth / span_y) / natural_y
            return natural_x * factor, natural_y * factor
        # XY: both pinned, so distortion is what was asked for.
        return reference.width / span_x, reference.depth / span_y

    @classmethod
    def _mesh_values(cls, source):
        """One number per face of a Ladybug chart's coloured mesh.

        The values live on the legend, not on the mesh, so they are read back
        from there — that also guarantees chart and legend share a scale."""
        if source is None:
            return None
        legend = getattr(source, "legend", None)
        values = getattr(legend, "values", None) if legend else None
        if not values:
            values = getattr(source, "values", None)
        if values:
            return list(values)
        return None

    @classmethod
    def _axis_number_labels(cls, output, chart, holder, specs):
        """Ladybug gives label POSITIONS for these charts but not always the
        label text, and the text varies by version. Where a matching *_text
        property exists it is used; otherwise the tick is drawn as a dot-free
        marker rather than inventing numbers."""
        for points_attribute, decimals in specs:
            points = getattr(chart, points_attribute, None)
            if not points:
                continue
            text_attribute = points_attribute.replace("_points", "_text")
            labels = getattr(chart, text_attribute, None)
            if not labels:
                # Some charts publish the positions but not the strings. The
                # values behind them are on the chart under the matching name,
                # so the label is built from those rather than skipped.
                values_attribute = points_attribute.replace("_label_points", "_labels")
                labels = getattr(chart, values_attribute, None)
            if not labels:
                continue
            for label, point in zip(labels, points):
                body = label
                if isinstance(label, (int, float)):
                    body = f"{label:.{decimals}f}"
                output.add_text(
                    points_attribute,
                    body,
                    (point.x, point.y, getattr(point, "z", 0.0)),
                    holder.text_size,
                )

