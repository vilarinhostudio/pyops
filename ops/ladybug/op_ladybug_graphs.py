    @classmethod
    def _build_comfort(cls, output, reference, holder, chart):
        """Comfort polygons over the chart that was just drawn."""

        epw = lb.load_epw(holder.epw)
        period = lb.analysis_period(holder)
        air_speed, mrt = cls._comfort_inputs(holder, epw, period)
        # These classes assert on list or tuple — a data collection is rejected
        # outright, so its values are unwrapped here rather than passed through.
        speed_arg = cls._as_list(air_speed)
        mrt_arg = cls._as_list(mrt)

        if holder.comfort_chart_type == "PMV":
            PolygonPMV = lb.optional("ladybug_comfort.chart.polygonpmv", "PolygonPMV")
            if PolygonPMV is None:
                print("[PyOps.ladybug] PMV exige ladybug-comfort.")
                return
            polygons = PolygonPMV(
                chart,
                rad_temperature=mrt_arg,
                air_speed=speed_arg,
                met_rate=[holder.metabolic_rate],
                clo_value=[holder.clothing],
                external_work=[holder.external_work],
            )
        else:
            PolygonUTCI = lb.optional("ladybug_comfort.chart.polygonutci", "PolygonUTCI")
            if PolygonUTCI is None:
                print("[PyOps.ladybug] UTCI exige ladybug-comfort.")
                return
            polygons = PolygonUTCI(
                chart,
                rad_temperature=mrt_arg,
                wind_speed=speed_arg,
            )

        if holder.show_comfort_zones:
            # UTCI publishes a polygon per stress band, which stacks a dozen
            # overlapping rings onto the chart. The merged comfort region is the
            # one that answers the question; the bands are available behind the
            # toggle for when they are the question.
            if holder.comfort_chart_type == "UTCI" and not holder.all_comfort_bands:
                merged = getattr(polygons, "comfort_polygon", None)
                shapes = [merged] if merged else list(polygons.comfort_polygons)[:1]
            else:
                shapes = list(polygons.comfort_polygons)
            for index, polygon in enumerate(shapes):
                if polygon:
                    output.add_curve(f"comfort_{index}", polygon, cyclic=True)
        if holder.legend:
            output.add_legend("comfort", getattr(polygons, "legend", None), holder.text_size)

        # Comfortable hours are the number this chart exists to produce.
        try:
            merged = polygons.create_collection(
                polygons.merged_comfort_data, "Comfort"
            ) if hasattr(polygons, "create_collection") else None
            data = merged or getattr(polygons, "merged_comfort_data", None)
            if data is not None:
                flags = list(getattr(data, "values", data))
                comfortable = sum(1 for flag in flags if flag)
                output.record(
                    lb_hours=len(flags),
                    lb_comfortable_hours=comfortable,
                    lb_comfortable_percent=round(
                        100.0 * comfortable / len(flags), 2
                    ) if flags else 0.0,
                )
        except Exception as e:
            print(f"[PyOps.ladybug] métricas de conforto indisponíveis: {e}")

