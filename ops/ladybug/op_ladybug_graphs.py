    @classmethod
    def _build_sun_path(cls, output, reference, holder):
        from ladybug.sunpath import Sunpath
        from ladybug_geometry.geometry3d.pointvector import Point3D

        epw = lb.load_epw(holder.epw)
        if epw is None:
            return
        # north_angle stays 0: +Y is north by convention, and that is exactly
        # how Ladybug measures it.
        location = epw.location
        sunpath = Sunpath(
            location.latitude,
            location.longitude,
            location.time_zone,
            north_angle=lb.NORTH_ANGLE,
        )
        origin = Point3D(0.0, 0.0, 0.0)
        radius = reference.radius(holder.scale)
        flat = holder.projection == "ORTHOGRAPHIC"

        # The 2D variants take a projection name first, not an origin — passing
        # a point there is what raised "'float' object has no attribute 'x'".
        # Projecting the 3D curves through the compass is one code path for both
        # modes and doesn't depend on that signature at all.
        analemmas = sunpath.hourly_analemma_polyline3d(origin, radius, True)
        day_arcs = sunpath.monthly_day_arc3d(origin, radius)
        if flat:
            compass = cls._compass(radius)
            analemmas = [c for c in (cls._flatten(a, compass) for a in analemmas) if c]
            # Day arcs are projected the same way. They were being drawn only in
            # the spherical mode, which left the orthographic chart with hour
            # loops and no dates to read them against.
            day_arcs = [c for c in (cls._flatten(a, compass) for a in day_arcs) if c]
        output.add_curve("analemmas", analemmas)
        output.add_curve("day_arcs", day_arcs)

        if holder.show_labels:
            cls._sunpath_labels(
                output, sunpath, origin, radius, flat, holder
            )

        period = lb.analysis_period(holder)
        suns = [sunpath.calculate_sun_from_hoy(hoy) for hoy in period.hoys]
        suns = [sun for sun in suns if sun.is_during_day]

        if suns and (holder.show_sun_points or holder.show_sun_vectors):
            positions = [cls._sun_position(sun, radius, flat) for sun in suns]

            if holder.show_sun_points:
                sun_mesh = lb.points_object("suns", positions, radius * 0.012 * holder.sun_size)
                sun_values = cls._sun_values(holder, epw, period, suns)
                if sun_mesh is not None and sun_values:
                    lb.set_face_values(sun_mesh, sun_values)
                    # The suns aren't a chart, so nothing built a legend for
                    # them — one is constructed here and its colours are baked
                    # onto the markers so the two agree.
                    legend = lb.build_legend(
                        sun_values,
                        cls._variable_label(holder.sun_value_variable),
                        origin=(radius * 1.15, -radius * 0.5, 0.0),
                        height=radius,
                    )
                    lb.apply_face_colors(sun_mesh, legend.value_colors)
                    if holder.legend:
                        output.add_legend(
                            "suns", legend, holder.text_size, holder.display_material
                        )
                    values = [v for v in sun_values if v is not None]
                    if values:
                        output.record(
                            lb_sun_value_min=round(min(values), 3),
                            lb_sun_value_max=round(max(values), 3),
                            lb_sun_value_mean=round(sum(values) / len(values), 3),
                        )
                elif sun_mesh is not None:
                    lb.set_face_values(sun_mesh, [s.altitude for s in suns])
                output.add_mesh(
                    "suns", sun_mesh, holder.display_material, "value"
                )
            if holder.show_sun_vectors:
                from ladybug_geometry.geometry3d.line import LineSegment3D

                output.add_curve(
                    "sun_vectors",
                    [
                        LineSegment3D.from_end_points(position, origin)
                        for position in positions
                    ],
                )

        if holder.show_compass:
            cls._add_compass(output, radius, holder, altitudes=flat)

        # Sunlit hours over the analysis period — the number this chart is
        # usually consulted for.
        total = len(period.hoys)
        output.record(
            lb_hours=total,
            lb_sunlit_hours=len(suns),
            lb_sunlit_percent=round(100.0 * len(suns) / total, 2) if total else 0.0,
            lb_sun_altitude_max=round(max((s.altitude for s in suns), default=0.0), 2),
        )

