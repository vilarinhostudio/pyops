    @classmethod
    def _build_wind(cls, output, reference, holder):
        epw = lb.load_epw(holder.epw)
        if epw is None:
            return
        period = lb.analysis_period(holder)

        if holder.wind_graph_type == "WIND_ROSE":
            WindRose = lb.optional("ladybug.windrose", "WindRose")
            if WindRose is None:
                return
            speed_data = lb.apply_period(epw.wind_speed, period)
            rose = WindRose(
                lb.apply_period(epw.wind_direction, period),
                speed_data,
                holder.direction_count,
            )
            rose.legend_parameters = lb.legend_parameters(holder, holder.title or None)
            radius = reference.radius(holder.scale)
            # compass_radius has no setter, so the rose is drawn at its own size
            # and the whole output is scaled to the reference instead.
            own_radius = getattr(rose, "compass_radius", 0.0) or 0.0
            if own_radius > 0:
                output.scale = radius / own_radius

            output.add_mesh(
                "wind_rose",
                lb.mesh_from_lb(
                    "wind_rose", rose.colored_mesh, cls._mesh_values(rose)
                ),
                holder.display_material,
                "value",
            )
            # Frequency rings close on themselves; the radial orientation
            # spokes do not.
            for attribute, cyclic in (
                ("orientation_lines", False),
                ("frequency_lines", True),
                ("windrose_lines", False),
            ):
                lines = getattr(rose, attribute, None)
                if lines:
                    output.add_curve(attribute, lines, cyclic=cyclic)
            if holder.legend:
                output.add_legend("wind_rose", rose.legend, holder.text_size, holder.display_material)
            if holder.show_compass:
                cls._add_compass(output, own_radius or radius, holder)

            values = list(speed_data.values)
            calm = sum(1 for value in values if value < 0.5)
            output.record(
                lb_hours=len(values),
                lb_wind_speed_mean=round(sum(values) / len(values), 3) if values else 0.0,
                lb_wind_speed_max=round(max(values), 3) if values else 0.0,
                lb_calm_hours=calm,
                lb_calm_percent=round(100.0 * calm / len(values), 2) if values else 0.0,
            )
            return

        WindProfile = lb.optional("ladybug.windprofile", "WindProfile")
        if WindProfile is None:
            return
        profile = WindProfile(terrain=holder.terrain_type)
        speed = lb.apply_period(epw.wind_speed, period)
        average = sum(speed.values) / len(speed.values) if len(speed) else 0.0
        try:
            result = profile.profile_polyline3d(
                average,
                holder.profile_height,
                max(holder.profile_height / 20.0, 0.5),
            )
        except TypeError as e:
            print(f"[PyOps.ladybug] profile_polyline3d: {e}")
            return
        # Returns (polyline, vectors, anchors) in some releases and a bare
        # polyline in others.
        polyline = result[0] if isinstance(result, (list, tuple)) else result
        output.add_curve("wind_profile", polyline)
        if holder.show_labels:
            output.add_text(
                "wind_profile_label",
                f"{average:.1f} m/s @ 10 m",
                (0.0, 0.0, holder.profile_height * 1.05),
                holder.text_size,
                align="LEFT",
            )
