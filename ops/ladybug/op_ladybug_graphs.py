    @classmethod
    def _sunpath_labels(cls, output, sunpath, origin, radius, flat, holder):
        """Dates on the day arcs and hours on the analemmas.

        Ladybug does not hand these over for a sun path the way a chart does, so
        each label is placed at a sun position computed for it: the date at its
        own solar noon, the hour at the highest point of its analemma. Both are
        pushed slightly outward so they sit clear of the curve they name."""
        from ladybug.analysisperiod import AnalysisPeriod

        compass = cls._compass(radius) if flat else None

        for month, day, text in cls.MONTH_LABELS:
            try:
                sun = sunpath.calculate_sun(month, day, 12)
            except Exception:
                continue
            if not sun.is_during_day:
                continue
            position = cls._sun_position(sun, radius * 1.04, flat)
            output.add_text(
                "month_label",
                text,
                (position.x, position.y, position.z),
                holder.text_size * 0.8,
                align="LEFT",
            )

        for hour in range(5, 20):
            best, best_altitude = None, -90.0
            for month, day, _text in cls.MONTH_LABELS:
                try:
                    sun = sunpath.calculate_sun(month, day, hour)
                except Exception:
                    continue
                if sun.is_during_day and sun.altitude > best_altitude:
                    best, best_altitude = sun, sun.altitude
            if best is None:
                continue
            position = cls._sun_position(best, radius * 1.08, flat)
            output.add_text(
                "hour_label",
                f"{hour:02d}h",
                (position.x, position.y, position.z),
                holder.text_size * 0.8,
            )

    @classmethod
    def _compass(cls, radius):
        from ladybug.compass import Compass
        from ladybug_geometry.geometry2d.pointvector import Point2D

        return Compass(radius, Point2D(0, 0), lb.NORTH_ANGLE)

    @classmethod
    def _flatten(cls, curve, compass):
        """3D curve → orthographic projection on the ground plane.

        Compass.point3d_to_orthographic is Ladybug's own projection, so the
        result matches what its other orthographic drawings look like. Points
        below the horizon have no projection and are dropped."""
        from ladybug_geometry.geometry3d.polyline import Polyline3D
        from ladybug_geometry.geometry3d.pointvector import Point3D

        points = []
        for vertex in getattr(curve, "vertices", []):
            if vertex.z < 0:
                continue
            flat = compass.point3d_to_orthographic(vertex)
            points.append(Point3D(flat.x, flat.y, 0.0))
        if len(points) < 2:
            return None
        return Polyline3D(points)

    @classmethod
    def _sun_position(cls, sun, radius, flat):
        """Sun position from altitude and azimuth, which every Ladybug version
        exposes on the Sun object.

        Azimuth is degrees clockwise from north, and +Y is north — so it maps to
        (sin, cos) rather than the usual (cos, sin). Orthographic drops the
        sphere onto the ground plane by scaling the radius with the cosine of
        the altitude."""
        from ladybug_geometry.geometry3d.pointvector import Point3D

        altitude = math.radians(sun.altitude)
        azimuth = math.radians(sun.azimuth)
        horizontal = radius * math.cos(altitude)
        position = Point3D(
            horizontal * math.sin(azimuth),
            horizontal * math.cos(azimuth),
            radius * math.sin(altitude),
        )
        if not flat:
            return position
        # Same projection as the curves, so suns land on their own analemmas.
        projected = cls._compass(radius).point3d_to_orthographic(position)
        return Point3D(projected.x, projected.y, 0.0)

    ALTITUDE_RINGS = (0, 15, 30, 45, 60, 75)

    @classmethod
    def _add_compass(cls, output, radius, holder, altitudes=False):
        """Compass ring, ticks and labels.

        `altitudes` adds the concentric altitude circles that make an
        orthographic sun path readable — without them the projection is just
        loops on a disc with no way to read a height off it."""
        compass = cls._compass(radius)
        for attribute, cyclic in (
            ("all_boundary_circles", True),
            ("inner_boundary_circle", True),
            ("major_azimuth_ticks", False),
            ("minor_azimuth_ticks", False),
        ):
            geometry = getattr(compass, attribute, None)
            if geometry:
                output.add_curve(attribute, geometry, cyclic=cyclic)

        if altitudes:
            cls._add_altitude_rings(output, radius, holder)

        if not holder.show_labels:
            return
        for text_attribute, point_attribute in (
            ("major_azimuth_text", "major_azimuth_points"),
            ("minor_azimuth_text", "minor_azimuth_points"),
        ):
            labels = getattr(compass, text_attribute, None)
            points = getattr(compass, point_attribute, None)
            if not labels or not points:
                continue
            size = holder.text_size * (1.0 if "major" in text_attribute else 0.7)
            for label, point in zip(labels, points):
                output.add_text(
                    "compass_label", label, (point.x, point.y, 0.0), size
                )

    @classmethod
    def _add_altitude_rings(cls, output, radius, holder):
        """Concentric circles at fixed altitudes, drawn through the same
        orthographic projection as everything else so they line up."""
        from ladybug_geometry.geometry3d.polyline import Polyline3D
        from ladybug_geometry.geometry3d.pointvector import Point3D

        compass = cls._compass(radius)
        for altitude in cls.ALTITUDE_RINGS:
            angle = math.radians(altitude)
            horizontal = radius * math.cos(angle)
            height = radius * math.sin(angle)
            points = []
            for step in range(73):
                azimuth = math.radians(step * 5)
                position = Point3D(
                    horizontal * math.sin(azimuth),
                    horizontal * math.cos(azimuth),
                    height,
                )
                flat = compass.point3d_to_orthographic(position)
                points.append(Point3D(flat.x, flat.y, 0.0))
            output.add_curve(f"altitude_{altitude}", Polyline3D(points))
            if holder.show_labels and altitude:
                output.add_text(
                    "altitude_label",
                    f"{altitude}\u00b0",
                    (0.0, points[0].y, 0.0),
                    holder.text_size * 0.7,
                    align="LEFT",
                )

    @classmethod
    def _build_dome(cls, output, reference, holder, module, class_name):
        """Radius, centre and projection belong to the CONSTRUCTOR here, not to
        draw() — draw() takes no arguments."""
        Dome = lb.optional(f"ladybug_radiance.visualize.{module}", class_name)
        if Dome is None:
            return
        matrix = cls._sky_matrix(holder)
        if matrix is None:
            return

        from ladybug_geometry.geometry3d.pointvector import Point3D

        radius = reference.radius(holder.scale)
        kwargs = {
            "legend_parameters": lb.legend_parameters(holder),
            "center_point": Point3D(0.0, 0.0, 0.0),
            "radius": radius,
            "projection": cls._projection(holder),
        }
        if class_name == "RadiationDome":
            kwargs["azimuth_count"] = holder.azimuth_count
            kwargs["altitude_count"] = holder.altitude_count

        dome = Dome(matrix, **kwargs)
        mesh, values, legend = cls._unpack_drawing(dome.draw())
        if mesh is None:
            return
        if values is None:
            values = cls._mesh_values(dome)
        blender_mesh = lb.mesh_from_lb(class_name.lower(), mesh, values, "value")
        if legend is not None:
            lb.apply_face_colors(blender_mesh, getattr(legend, "value_colors", None))
        output.add_mesh(
            class_name.lower(), blender_mesh, holder.display_material, "value"
        )
        if holder.legend and legend is not None:
            output.add_legend(
                class_name.lower(), legend, holder.text_size, holder.display_material
            )
        if holder.show_compass:
            cls._add_compass(output, radius, holder)
        cls._record_values(output, values)

    @classmethod
    def _projection(cls, holder):
        return None if holder.projection == "SPHERICAL" else "Orthographic"

    @classmethod
    def _build_radiation_rose(cls, output, reference, holder):
        RadiationRose = lb.optional(
            "ladybug_radiance.visualize.radrose", "RadiationRose"
        )
        if RadiationRose is None:
            return
        matrix = cls._sky_matrix(holder)
        if matrix is None:
            return
        radius = reference.radius(holder.scale)
        from ladybug_geometry.geometry3d.pointvector import Point3D

        rose = RadiationRose(
            matrix,
            direction_count=holder.direction_count,
            legend_parameters=lb.legend_parameters(holder),
            center_point=Point3D(0.0, 0.0, 0.0),
            radius=radius,
        )
        mesh, values, legend = cls._unpack_drawing(rose.draw())
        if mesh is None:
            return
        if values is None:
            values = cls._mesh_values(rose)
        blender_mesh = lb.mesh_from_lb("radiation_rose", mesh, values, "value")
        if legend is not None:
            lb.apply_face_colors(blender_mesh, getattr(legend, "value_colors", None))
        output.add_mesh(
            "radiation_rose", blender_mesh, holder.display_material, "value"
        )
        if holder.legend and legend is not None:
            output.add_legend(
                "radrose", legend, holder.text_size, holder.display_material
            )
        if holder.show_compass:
            cls._add_compass(output, radius, holder)
        cls._record_values(output, values)

    @classmethod
    def _unpack_drawing(cls, result):
        """`draw()` returns a tuple whose shape has moved between releases —
        pick the mesh, the values and the legend out by type instead of by
        position."""
        mesh = values = legend = None
        items = result if isinstance(result, (list, tuple)) else [result]
        for item in items:
            if item is None:
                continue
            if hasattr(item, "faces") and hasattr(item, "vertices"):
                if mesh is None:  # the first mesh is the graph; later ones are
                    mesh = item   # the compass and title, drawn separately
            elif hasattr(item, "segment_mesh"):
                legend = item
            elif hasattr(item, "legend"):
                # A GraphicContainer: it wraps the legend rather than being one,
                # which is why looking only for segment_mesh found nothing and
                # every radiation graph came out without a key.
                legend = item.legend
                container_values = getattr(item, "values", None)
                if container_values and values is None:
                    values = list(container_values)
            elif isinstance(item, (list, tuple)) and item and isinstance(
                item[0], (int, float)
            ):
                values = list(item)

        if values is None and legend is not None:
            legend_values = getattr(legend, "values", None)
            if legend_values:
                values = list(legend_values)
        return mesh, values, legend

    @classmethod
    def _sky_matrix(cls, holder):
        """SkyMatrix is built from a Wea, not from an EPW path.

        Generating it calls Radiance's gendaymtx, so this is the one graph
        family that needs Radiance installed on the machine beyond pip."""
        SkyMatrix = lb.optional("ladybug_radiance.skymatrix", "SkyMatrix")
        if SkyMatrix is None:
            return None
        path = bpy.path.abspath(holder.epw) if holder.epw else ""
        if not path:
            print("[PyOps.ladybug] Nenhum EPW informado.")
            return None
        try:
            from ladybug.wea import Wea

            wea = Wea.from_epw_file(path)
            if holder.sky_matrix_mode != "ANNUAL":
                period = lb.analysis_period(holder)
                wea = wea.filter_by_analysis_period(period)
            return SkyMatrix(wea, north=lb.NORTH_ANGLE)
        except Exception as e:
            print(f"[PyOps.ladybug] SkyMatrix: {e}")
            print("[PyOps.ladybug] Este gráfico requer o Radiance instalado (gendaymtx).")
            return None

