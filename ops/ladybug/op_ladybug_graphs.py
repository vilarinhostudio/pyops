    @classmethod
    def _psych_chart(cls, reference, holder):
        PsychrometricChart = lb.optional(
            "ladybug.psychchart", "PsychrometricChart"
        )
        if PsychrometricChart is None:
            return None
        epw = lb.load_epw(holder.epw)
        if epw is None:
            return None
        period = lb.analysis_period(holder)
        from ladybug_geometry.geometry2d.pointvector import Point2D

        # x_dim is per DEGREE and y_dim per unit of humidity ratio, so the
        # dimensions come from the chart's own axis ranges — not from a guess.
        min_temperature, max_temperature = -20.0, 50.0
        max_humidity_ratio = 0.03
        # Ladybug's natural dimensions: one unit per degree across, 1500 per
        # unit of humidity ratio up. Everything else is a scale on that pair, so
        # the chart never distorts unless BOTH axes are pinned.
        x_dim, y_dim = cls._chart_dims(
            reference,
            holder,
            natural_x=1.0,
            natural_y=1500.0,
            span_x=max_temperature - min_temperature,
            span_y=max_humidity_ratio,
        )
        return PsychrometricChart(
            lb.apply_period(epw.dry_bulb_temperature, period),
            lb.apply_period(epw.relative_humidity, period),
            average_pressure=holder.pressure,
            legend_parameters=lb.legend_parameters(holder, holder.title or None),
            base_point=Point2D(reference.min[0], reference.min[1]),
            x_dim=x_dim,
            y_dim=y_dim,
            min_temperature=min_temperature,
            max_temperature=max_temperature,
            max_humidity_ratio=max_humidity_ratio,
        )

