"""Ladybug Tools climate graphs as Blender geometry.

One operator, one Enum, conditional inputs — no node system, no per-graph
operators. Every graph is generated by Ladybug's own Python API and converted to
Blender meshes, curves and text; nothing is rasterised and nothing is downloaded.

Two conventions run through the whole file.

Blender's +Y is north, always. Ladybug measures north as a clockwise angle from
+Y, so that convention makes the offset zero and there is no north input.

The parent object is the spatial reference. Charts are laid out in its local
space and the generated objects inherit its transform, so moving or rotating the
reference carries its graphs along. The parent supplies origin, bounding box and
scale; it is not part of the visual result.

Graphs backed by an optional Ladybug package (comfort, radiance) report a
controlled warning when it is missing instead of failing the operation.
"""

